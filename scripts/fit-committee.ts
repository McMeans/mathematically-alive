// Fit the committee stand-in's weights (src/core/committee.ts) to past committee rankings, and write them to
// src/core/committee-weights.ts. Usage: pnpm fit-committee. Reads fixtures/cfp-<year>.json (made by pnpm cfp); no
// API calls. Each season's latest ranking in the fixtures is used: the final one for finished seasons, otherwise the
// newest of the season being played. Its features come from games before the ranking's week.
//
// Model: the committee puts team a above team b with probability 1 / (1 + e^-(score(a) - score(b))), the score
// linear in the features. Fitted by maximum likelihood over every ordered pair the ranking states (two ranked teams,
// or a ranked team over an unranked FBS team), each ranking weighted equally, with a small ridge penalty. That pair
// model is also why the simulation adds standard Gumbel noise to each score: it gives those same pair odds.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { committeeRanking, seasonFromCfbd, type CfbdSnapshot, type CommitteeFeatures } from "../src/core";

type Fixture = { snapshot: CfbdSnapshot; rankings: { week: number; ranks: { rank: number; teamId: number }[] }[] };

const KEYS = ["wins", "losses", "rating", "strength", "champion"] as const;
const RIDGE = 0.01;

const vec = (f: CommitteeFeatures): number[] => KEYS.map((k) => f[k]);

function main() {
  const files = readdirSync("fixtures").filter((f) => /^cfp-\d{4}\.json$/.test(f)).sort();
  if (files.length === 0) throw new Error("No fixtures/cfp-<year>.json. Run pnpm cfp first.");
  // One list of feature differences (winner minus loser) per ranking.
  const groups: number[][][] = [];
  for (const file of files) {
    const fx = JSON.parse(readFileSync(path.join("fixtures", file), "utf8")) as Fixture;
    const season = seasonFromCfbd(fx.snapshot);
    const latest = fx.rankings[fx.rankings.length - 1];
    const rows = committeeRanking(season, { throughWeek: latest.week - 1 });
    const feat = new Map(rows.map((r) => [r.teamId, vec({ ...r, champion: r.champion ? 1 : 0 })]));
    const ranked = latest.ranks.map((r) => r.teamId).filter((id) => feat.has(id));
    const rankedSet = new Set(ranked);
    const unranked = rows.map((r) => r.teamId).filter((id) => !rankedSet.has(id));
    const diffs: number[][] = [];
    const diff = (a: number, b: number) => feat.get(a)!.map((x, k) => x - feat.get(b)![k]);
    ranked.forEach((a, i) => {
      for (const b of ranked.slice(i + 1)) diffs.push(diff(a, b));
      for (const b of unranked) diffs.push(diff(a, b));
    });
    groups.push(diffs);
  }

  // Newton's method on the penalized log-likelihood.
  const n = KEYS.length;
  let w = new Array<number>(n).fill(0);
  for (let iter = 0; iter < 50; iter++) {
    const grad = w.map((x) => -RIDGE * x);
    const hess = Array.from({ length: n }, (_, i) => Array.from({ length: n }, (_, j) => (i === j ? -RIDGE : 0)));
    for (const diffs of groups) {
      const scale = 1 / diffs.length;
      for (const d of diffs) {
        const z = d.reduce((s, x, k) => s + x * w[k], 0);
        const p = 1 / (1 + Math.exp(-z));
        for (let i = 0; i < n; i++) {
          grad[i] += scale * (1 - p) * d[i];
          for (let j = 0; j < n; j++) hess[i][j] -= scale * p * (1 - p) * d[i] * d[j];
        }
      }
    }
    const step = solve(hess, grad.map((g) => -g));
    w = w.map((x, k) => x + step[k]);
    if (Math.max(...step.map(Math.abs)) < 1e-10) break;
  }

  const weights = Object.fromEntries(KEYS.map((k, i) => [k, Number(w[i].toPrecision(4))]));
  const out = path.join("src", "core", "committee-weights.ts");
  writeFileSync(out, `// Generated by scripts/fit-committee.ts (pnpm fit-committee) from ${files.length} seasons of fixtures/cfp-<year>.json. Do not hand-edit.
export const COMMITTEE_WEIGHTS = ${JSON.stringify(weights).replace(/"/g, "").replace(/,/g, ", ").replace(/:/g, ": ").replace(/^\{/, "{ ").replace(/\}$/, " }")};
`);
  console.log(`${out}: ${JSON.stringify(weights)} from ${groups.length} rankings`);
}

/** Solve a x = b by Gaussian elimination with partial pivoting. */
function solve(a: number[][], b: number[]): number[] {
  const n = b.length;
  const m = a.map((row, i) => [...row, b[i]]);
  for (let c = 0; c < n; c++) {
    let p = c;
    for (let r = c + 1; r < n; r++) if (Math.abs(m[r][c]) > Math.abs(m[p][c])) p = r;
    [m[c], m[p]] = [m[p], m[c]];
    for (let r = c + 1; r < n; r++) {
      const f = m[r][c] / m[c][c];
      for (let k = c; k <= n; k++) m[r][k] -= f * m[c][k];
    }
  }
  const x = new Array<number>(n).fill(0);
  for (let r = n - 1; r >= 0; r--) {
    let s = m[r][n];
    for (let k = r + 1; k < n; k++) s -= m[r][k] * x[k];
    x[r] = s / m[r][r];
  }
  return x;
}

main();
